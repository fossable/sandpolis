/// Names a _layer_: the GUI face a subsystem presents, which the client's layer
/// picker chooses between and which notifications and services are attributed
/// to. A subsystem provides at most one, so the layer's name is the subsystem's
/// name (e.g. `"Shell"`, `"Inventory"`).
///
/// Layers are registered at runtime using the `inventory` crate.
#[cfg_attr(feature = "client", derive(bevy::prelude::Resource))]
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
pub struct LayerName(pub String);

impl LayerName {
    /// Create a new layer with the given name.
    pub const fn new(name: String) -> Self {
        Self(name)
    }

    /// Get the layer name.
    pub fn name(&self) -> &str {
        &self.0
    }

    /// Iterate over all registered layers.
    pub fn registered() -> impl Iterator<Item = &'static LayerName> {
        inventory::iter::<LayerName>()
    }
}

impl std::fmt::Display for LayerName {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

impl std::ops::Deref for LayerName {
    type Target = str;

    fn deref(&self) -> &Self::Target {
        &self.0
    }
}

impl From<&str> for LayerName {
    fn from(s: &str) -> Self {
        Self(s.to_string())
    }
}

impl From<String> for LayerName {
    fn from(s: String) -> Self {
        Self(s)
    }
}

impl PartialEq<str> for LayerName {
    fn eq(&self, other: &str) -> bool {
        self.0 == other
    }
}

impl PartialEq<&str> for LayerName {
    fn eq(&self, other: &&str) -> bool {
        self.0 == *other
    }
}

