#[derive(Clone)]
#[cfg_attr(feature = "client", derive(bevy::prelude::Resource))]
pub struct InstanceManager {
    /// Every domain in the estate. Assigned by the global stratum server and
    /// replicated from there, so this is a read-only view everywhere else.
    domains: ResidentVec<DomainData>,
    /// Every instance in the estate, replicated in. The client's world view is
    /// drawn from this, so it covers instances this one never talks to.
    instances: ResidentVec<InstanceManagerData>,
    /// The default realm, so callers that need one (the service runner, say)
    /// don't have to be handed the whole [`DatabaseManager`].
    realm: crate::database::RealmDatabase,
    pub instance_id: InstanceId,
    pub cluster_id: ClusterId,
}

impl InstanceManager {
    /// `instance_type` is what this process was started as, which is what its
    /// identity says about it forever after.
    pub async fn new(database: DatabaseManager, instance_type: InstanceType) -> Result<Self> {
        let realm = database.realm(RealmName::default())?;

        // The identity row is generated on first start and reused forever after.
        // It is seeded as instance-local bookkeeping rather than through the
        // scope gate: the row's own scope is this instance's id, which isn't
        // known until the row exists.
        {
            let r = realm.r_transaction()?;
            let existing = r
                .scan()
                .primary::<InstanceManagerData>()?
                .all()?
                .next()
                .transpose()?;
            drop(r);

            if existing.is_none() {
                let rw = realm.local_write()?;
                rw.insert(InstanceManagerData {
                    _instance_id: InstanceId::new(instance_type),
                    ..Default::default()
                })?;
                rw.commit()?;
            }
        }

        let data: Resident<InstanceManagerData> = realm.resident(())?;

        let instance_id = data.read()._instance_id;

        // A data directory belongs to the instance that created it. Running a
        // different instance against it would mean two instances sharing one
        // identity, which is exactly what this identity exists to prevent.
        if !instance_id.is_type(instance_type) {
            bail!(
                "This data directory belongs to a {:?} instance ({instance_id}), \
                 so a {instance_type:?} cannot run against it. Give each instance \
                 its own --data directory.",
                instance_id.instance_type()
            );
        }

        // With scoped authority, the self scope becomes writable from here on.
        if let Some(table) = database.authority().scope_table() {
            table.set_self(instance_id);
        }

        // Every subsystem raises notifications through a process-wide handle, so it
        // is installed here — the first point that knows both the database and
        // this instance's id. Idempotent, since startup builds an `InstanceManager`
        // more than once.
        crate::notification::install(&realm, instance_id);

        Ok(Self {
            instance_id,
            cluster_id: { data.read().cluster_id },
            domains: realm.resident_vec(())?,
            instances: realm.resident_vec(())?,
            realm,
        })
    }

    /// What this process is: agent, client, or server.
    pub fn instance_type(&self) -> InstanceType {
        self.instance_id
            .instance_type()
            .expect("the local instance id always names a type")
    }

    /// The domain the given instance belongs to, if any.
    ///
    /// Servers are never members, so the rule is applied here too: a server that
    /// somehow appears in a domain's member list still resolves to nothing.
    pub fn domain_of(&self, id: InstanceId) -> Option<String> {
        if !id.is_domain_member() {
            return None;
        }

        self.domains.iter().find_map(|domain| {
            let domain = domain.read();
            domain
                .members
                .contains(&id)
                .then(|| domain.name.trim().to_string())
                .filter(|name| !name.is_empty())
        })
    }

    /// Every domain in the estate.
    pub fn domains(&self) -> &ResidentVec<DomainData> {
        &self.domains
    }

    /// Every instance the estate knows about, this one included.
    ///
    /// A client draws a node per entry, which is how an agent it holds no
    /// connection to shows up at all.
    pub fn instances(&self) -> &ResidentVec<InstanceManagerData> {
        &self.instances
    }

    /// This instance's default realm.
    pub fn realm(&self) -> &crate::database::RealmDatabase {
        &self.realm
    }
}

#[derive(Serialize, Deserialize, Clone, Debug, PartialEq, Eq)]
pub struct LayerVersion {
    pub major: u32,
    pub minor: u32,
    pub patch: u32,
    pub description: Option<String>,
    // pub rev: Option<String>,
    // pub build_time: Option<String>,
}

impl TryFrom<String> for LayerVersion {
    type Error = anyhow::Error;

    /// Parse `major.minor.patch` with an optional `-description` suffix, which
    /// is the shape cargo's `CARGO_PKG_VERSION` takes.
    fn try_from(value: String) -> Result<Self, Self::Error> {
        let (numbers, description) = match value.split_once('-') {
            Some((numbers, description)) => (numbers, Some(description.to_string())),
            None => (value.as_str(), None),
        };

        let mut parts = numbers.split('.');
        let mut number = |field: &str| -> Result<u32, Self::Error> {
            parts
                .next()
                .ok_or_else(|| anyhow::anyhow!("missing {field} version in: {value}"))?
                .parse()
                .map_err(|_| anyhow::anyhow!("invalid {field} version in: {value}"))
        };

        let major = number("major")?;
        let minor = number("minor")?;
        let patch = number("patch")?;

        if parts.next().is_some() {
            anyhow::bail!("trailing version component in: {value}");
        }

        Ok(Self {
            major,
            minor,
            patch,
            description,
        })
    }
}

impl PartialOrd for LayerVersion {
    fn partial_cmp(&self, other: &Self) -> Option<Ordering> {
        Some(self.cmp(other))
    }
}

impl Ord for LayerVersion {
    fn cmp(&self, other: &Self) -> Ordering {
        if self.major > other.major {
            Ordering::Greater
        } else if self.major < other.major {
            Ordering::Less
        } else if self.minor > other.minor {
            Ordering::Greater
        } else if self.minor < other.minor {
            Ordering::Less
        } else if self.patch > other.patch {
            Ordering::Greater
        } else if self.patch < other.patch {
            Ordering::Less
        } else {
            Ordering::Equal
        }
    }
}

