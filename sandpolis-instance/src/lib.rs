/// All instances are identified by a unique 128-bit string that's generated on
/// first start. This identifier is reused for all subsequent runs.
#[cfg_attr(feature = "client", derive(bevy::prelude::Component))]
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub struct InstanceId(u128);

// `serde_cbor` cannot encode `u128`, so represent the id as its raw little-endian
// bytes. This is format-agnostic (CBOR, JSON, etc.) and consistent across peers.
impl Serialize for InstanceId {
    fn serialize<S: serde::Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {
        self.0.to_le_bytes().serialize(serializer)
    }
}

impl<'de> Deserialize<'de> for InstanceId {
    fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        Ok(InstanceId(u128::from_le_bytes(<[u8; 16]>::deserialize(
            deserializer,
        )?)))
    }
}

impl InstanceId {
    /// Generate a new instance ID for an instance of the given type.
    pub fn new(instance_type: InstanceType) -> Self {
        // A v7 uuid leads with its timestamp, so ids generated near each other
        // share a long prefix. `format_uuid` renders the low bytes first, which
        // reverses that: the random bytes come first and two ids differ from the
        // start. It also keeps the timestamp clear of the nibble below, which is
        // what makes `timestamp` recoverable.
        let mut uuid = Uuid::now_v7().as_u128();

        // Wipe out last nibble
        uuid &= 0xFFFFFFFFFFFFFFFFFFFFFFFFFFFFFFF0;

        uuid |= instance_type.mask() as u128;

        trace!(id = uuid, "Generated new instance ID");
        Self(uuid)
    }

    /// Generate a new server ID as a convenience.
    pub fn new_server() -> Self {
        Self::new(InstanceType::Server)
    }

    /// Check whether this UUID was generated with the given instance type.
    pub fn is_type(&self, instance_type: InstanceType) -> bool {
        self.0 & instance_type.mask() as u128 > 0
    }

    pub fn is_server(&self) -> bool {
        self.is_type(InstanceType::Server)
    }

    pub fn is_client(&self) -> bool {
        self.is_type(InstanceType::Client)
    }

    pub fn is_agent(&self) -> bool {
        self.is_type(InstanceType::Agent)
    }

    /// Whether an instance of this type can belong to a domain. Domains group
    /// the estate, not the servers running it.
    pub fn is_domain_member(&self) -> bool {
        self.is_agent() || self.is_client()
    }

    /// Return the instance type encoded in this UUID, or `None` if it names no
    /// instance (see [`Default`]).
    pub fn instance_type(&self) -> Option<InstanceType> {
        InstanceType::iter().find(|t| self.is_type(*t))
    }

    /// Return when this id was generated, in milliseconds since the unix epoch.
    ///
    /// This is the v7 uuid's own timestamp, so it's only as trustworthy as the
    /// clock of whatever instance generated the id. Zero for [`Default`], which
    /// was never generated at all.
    pub fn timestamp(&self) -> u64 {
        // v7 puts a 48-bit millisecond timestamp in the uuid's leading bytes,
        // which `new` leaves untouched.
        (self.0 >> 80) as u64
    }
}

/// The id that names no instance. Data models derive `Default`, so every
/// `InstanceId` field starts here and is overwritten with a real id by whatever
/// knows one. Nothing is ever generated by default, which would look like a real
/// instance nobody can reach.
impl Default for InstanceId {
    fn default() -> Self {
        Self(0)
    }
}

impl Display for InstanceId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(std::str::from_utf8(&format_uuid(self.0)).unwrap())
    }
}

impl FromStr for InstanceId {
    type Err = anyhow::Error;

    /// Inverse of [`Display`]: parse the uuid-formatted string back into the
    /// little-endian bytes used to construct it.
    fn from_str(s: &str) -> Result<Self> {
        let hex: String = s.chars().filter(|c| *c != '-').collect();
        if hex.len() != 32 {
            anyhow::bail!("invalid InstanceId: {s}");
        }
        let mut bytes = [0u8; 16];
        for (i, byte) in bytes.iter_mut().enumerate() {
            *byte = u8::from_str_radix(&hex[i * 2..i * 2 + 2], 16)?;
        }
        Ok(InstanceId(u128::from_le_bytes(bytes)))
    }
}

impl ToKey for InstanceId {
    fn to_key(&self) -> native_db::Key {
        native_db::Key::new(self.0.to_be_bytes().to_vec())
    }

    fn key_names() -> Vec<String> {
        vec!["InstanceId".to_string()]
    }
}

/// All possible instance types.
#[derive(
    Serialize, Deserialize, Clone, Copy, EnumIter, Debug, PartialEq, Eq, PartialOrd, Ord, Hash,
)]
pub enum InstanceType {
    /// Runs continuously on hosts and responds to management requests from
    /// servers and clients.
    Agent,

    /// User interface for managing instances in the Sandpolis network.
    Client,

    /// Runs continously and coordinates interactions among instances in a
    /// Sandpolis network. All networks include at least one server
    /// instance.
    Server,
    // Probes are not technically instances, but they can connect to proper
    // agents/server instances and appear like standalone instances.
}

impl InstanceType {
    /// Each instance type has an identifier.
    pub const fn mask(&self) -> u8 {
        match self {
            InstanceType::Agent => 0b00000001,
            InstanceType::Client => 0b00000010,
            InstanceType::Server => 0b00000100,
        }
    }

    /// Each instance type has an associated color.
    pub const fn color(&self) -> colored::Color {
        match self {
            InstanceType::Agent => colored::Color::Cyan,
            InstanceType::Client => colored::Color::Green,
            InstanceType::Server => colored::Color::Magenta,
        }
    }
}

